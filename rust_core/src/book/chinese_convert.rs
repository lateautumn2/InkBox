fn s2t_map() -> &'static HashMap<char, char> {
    static MAP: OnceLock<HashMap<char, char>> = OnceLock::new();
    MAP.get_or_init(|| {
        let mut m = HashMap::with_capacity(S2T_PAIRS.len());
        for (s, t) in S2T_PAIRS {
            if let (Some(sc), Some(tc)) = (s.chars().next(), t.chars().next()) {
                m.entry(sc).or_insert(tc);
            }
        }
        m
    })
}

fn t2s_map() -> &'static HashMap<char, char> {
    static MAP: OnceLock<HashMap<char, char>> = OnceLock::new();
    MAP.get_or_init(|| {
        let mut m = HashMap::with_capacity(S2T_PAIRS.len());
        for (s, t) in S2T_PAIRS {
            if let (Some(sc), Some(tc)) = (s.chars().next(), t.chars().next()) {
                m.entry(tc).or_insert(sc);
            }
        }
        m
    })
}

pub fn convert_chinese(input: &str, mode: ChineseConversionMode) -> String {
    match mode {
        ChineseConversionMode::None => input.to_string(),
        ChineseConversionMode::ToTraditional => {
            let map = s2t_map();
            input.chars().map(|c| *map.get(&c).unwrap_or(&c)).collect()
        }
        ChineseConversionMode::ToSimplified => {
            let map = t2s_map();
            input.chars().map(|c| *map.get(&c).unwrap_or(&c)).collect()
        }
    }
}

